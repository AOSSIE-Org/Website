#!/usr/bin/env node
/**
 * Refreshes src/lib/repoStats.ts with current GitHub stars and last-push dates
 * for every repository listed in src/lib/projectsData.ts.
 *
 * Usage:  npm run update:stats
 * Set GITHUB_TOKEN to avoid the unauthenticated rate limit (60 requests/hour).
 */
import { readFile, writeFile } from "node:fs/promises";

const DATA_FILE = new URL("../src/lib/projectsData.ts", import.meta.url);
const STATS_FILE = new URL("../src/lib/repoStats.ts", import.meta.url);

const source = await readFile(DATA_FILE, "utf8");
const repos = [...new Set([...source.matchAll(/fullName: "([^"]+)"/g)].map((m) => m[1]))].sort();

const headers = { Accept: "application/vnd.github+json", "User-Agent": "aossie-website" };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

let failed = 0;
const stats = {};
for (const repo of repos) {
  const res = await fetch(`https://api.github.com/repos/${repo}`, { headers });
  if (!res.ok) {
    failed++;
    console.error(`✗ ${repo}: ${res.status} ${res.statusText}`);
    if (res.status === 403 || res.status === 429) {
      console.error("Rate limited. Set GITHUB_TOKEN and try again.");
      process.exit(1);
    }
    continue;
  }
  const data = await res.json();
  stats[repo] = { stars: data.stargazers_count, pushedAt: data.pushed_at.slice(0, 10) };
  console.log(`✓ ${repo}: ${data.stargazers_count}★`);
}

if (failed > 0) {
  console.error(`\nEncountered ${failed} failed lookup(s). Aborting without updating src/lib/repoStats.ts.`);
  process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);
const lines = Object.entries(stats).map(
  ([name, s]) => `  "${name}": { stars: ${s.stars}, pushedAt: "${s.pushedAt}" },`
);
const output = `/**
 * Snapshot of GitHub repository stats (stars, last push), used to rank projects.
 * Generated by \`npm run update:stats\` on ${today}. Do not edit by hand.
 */
export const REPO_STATS: Record<string, { stars: number; pushedAt: string }> = {
${lines.join("\n")}
};
`;
await writeFile(STATS_FILE, output);
console.log(`\nWrote ${Object.keys(stats).length} repositories to src/lib/repoStats.ts`);
